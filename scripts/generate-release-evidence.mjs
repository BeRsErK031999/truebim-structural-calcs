import { execSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outputDir = path.resolve(rootDir, process.env.RELEASE_EVIDENCE_OUTPUT_DIR ?? 'release-evidence')
const packageJson = JSON.parse(readFileSync(path.join(rootDir, 'package.json'), 'utf-8'))
const generatedAt = process.env.RELEASE_EVIDENCE_DATE ?? new Date().toISOString()
const commitHash = getGitCommit()
const shortCommit = sanitizeFileSegment(commitHash).slice(0, 12) || 'unknown'
const dateSegment = generatedAt.slice(0, 10)
const basename = `release-evidence-${shortCommit}-${dateSegment}`

const evidence = {
  commitHash,
  appVersion: packageJson.version,
  buildTime: generatedAt,
  generatedAt,
  testStatus: buildStatus(
    'unknown',
    'Test status',
    process.env.RELEASE_TEST_STATUS ?? 'Attach the latest npm run test result for release audit.',
  ),
  deployPrecheckStatus: buildStatus(
    'unknown',
    'Deploy precheck',
    process.env.RELEASE_DEPLOY_PRECHECK_STATUS ?? 'Attach the latest npm run deploy:precheck result for release audit.',
  ),
  officeUrlsStatus: await checkOfficeUrls(),
  diagnosticsSummary: {
    appLoaded: 'unknown',
    environment: process.env.NODE_ENV ?? 'production',
    localStorageAvailable: 'unknown',
    savedCalculationsCount: 'unknown',
    warning: 'Generated by local CLI without requiring backend or browser runtime.',
  },
  verificationSummary: buildVerificationSummary(),
  verificationCapabilityMatrix: buildCapabilityMatrix(),
  counts: buildCounts(),
  validationSessionStatus: {
    support: 'local-only',
    sessionsCount: 'unknown',
    engineerPackageReady: 'unknown',
    checklistProgressSupport: 'yes',
    packageExportSupport: 'manifest',
  },
  reviewCandidateStatus: {
    reviewModeSupport: 'local-only',
    candidateSupport: 'yes',
    autoPromotion: 'no',
    manualDatasetImportRequired: 'yes',
    frozenSnapshotsCount: 'unknown',
    pendingReviewsCount: 'unknown',
    acceptedReviewsCount: 'unknown',
    rejectedReviewsCount: 'unknown',
  },
  knownWarnings: [
    'Evidence bundle is audit-only and does not promote draft or partial cases to VERIFIED.',
    'Server URL checks are warning-only and do not require backend availability.',
  ],
  rollbackNotes: [
    'Use the release evidence bundle to identify the deployed commit before rollback.',
    'Follow docs/release-checklist.md rollback commands for the project container only.',
    'After rollback, regenerate evidence and compare diagnostics, URLs, and verification matrix.',
  ],
}

for (const urlStatus of evidence.officeUrlsStatus) {
  if (urlStatus.status !== 'pass') {
    evidence.knownWarnings.push(`${urlStatus.url}: ${urlStatus.details}`)
  }
}

mkdirSync(outputDir, { recursive: true })
writeFileSync(path.join(outputDir, `${basename}.json`), JSON.stringify(evidence, null, 2))
writeFileSync(path.join(outputDir, `${basename}.md`), buildMarkdown(evidence))
writeFileSync(path.join(outputDir, `${basename}.html`), buildHtml(evidence))

console.log(`Release evidence generated: ${path.relative(rootDir, outputDir)}\\${basename}.{json,md,html}`)

function getGitCommit() {
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd: rootDir,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return 'unknown'
  }
}

async function checkOfficeUrls() {
  const urls = (process.env.RELEASE_EVIDENCE_URLS ?? 'http://192.168.22.37,http://truebim-calc.local')
    .split(',')
    .map((url) => url.trim())
    .filter(Boolean)

  if (process.env.RELEASE_EVIDENCE_SKIP_URL_CHECK === '1') {
    return urls.map((url) => ({
      ...buildStatus('warning', 'Office URL', 'Skipped by RELEASE_EVIDENCE_SKIP_URL_CHECK.'),
      url,
    }))
  }

  return Promise.all(urls.map(checkUrl))
}

async function checkUrl(url) {
  const checkedAt = new Date().toISOString()

  try {
    const response = await fetch(url, {
      method: 'GET',
      signal: AbortSignal.timeout(3000),
    })

    return {
      status: response.ok ? 'pass' : 'warning',
      label: 'Office URL',
      details: `HTTP ${response.status}`,
      checkedAt,
      url,
    }
  } catch (error) {
    return {
      status: 'warning',
      label: 'Office URL',
      details: `Unavailable during evidence generation: ${error instanceof Error ? error.message : String(error)}`,
      checkedAt,
      url,
    }
  }
}

function buildVerificationSummary() {
  const statuses = readVerificationStatuses()
  const verifiedCases = statuses.filter((status) => status === 'verified').length

  return {
    totalCases: statuses.length,
    draftCases: statuses.filter((status) => status === 'draft').length,
    verifiedCases,
    rejectedCases: statuses.filter((status) => status === 'rejected').length,
    passedCases: 0,
    failedCases: 0,
    warning: verifiedCases === 0 ? 'No SP63 verified cases yet' : null,
  }
}

function buildCounts() {
  const statuses = readVerificationStatuses()

  return {
    verified: statuses.filter((status) => status === 'verified').length,
    draft: statuses.filter((status) => status === 'draft').length,
    partial: buildCapabilityMatrix().filter((capability) => capability.status === 'partial').length,
  }
}

function buildCapabilityMatrix() {
  const source = readFileSync(
    path.join(rootDir, 'src/calculations/punching-shear/verified/verifiedCapabilities.ts'),
    'utf-8',
  )

  return Array.from(source.matchAll(/id: '([^']+)'[\s\S]*?label: '([^']+)'[\s\S]*?status: '([^']+)'[\s\S]*?arithmeticSupport: '([^']+)'[\s\S]*?notes: '([^']+)'/g)).map(
    (match) => ({
      id: match[1],
      label: match[2],
      status: match[3],
      arithmeticSupport: match[4],
      notes: match[5],
    }),
  )
}

function readVerificationStatuses() {
  const source = readFileSync(
    path.join(rootDir, 'src/calculations/punching-shear/verification/verificationDataset.ts'),
    'utf-8',
  )

  return Array.from(source.matchAll(/status: '(verified|draft|rejected)'/g)).map((match) => match[1])
}

function buildMarkdown(bundle) {
  return [
    `# Release Evidence ${bundle.commitHash}`,
    '',
    `- Commit: ${bundle.commitHash}`,
    `- Version: ${bundle.appVersion}`,
    `- Build time: ${bundle.buildTime}`,
    `- Generated at: ${bundle.generatedAt}`,
    `- Test status: ${bundle.testStatus.status} - ${bundle.testStatus.details}`,
    `- Deploy precheck: ${bundle.deployPrecheckStatus.status} - ${bundle.deployPrecheckStatus.details}`,
    '',
    '## Counts',
    `- Verified: ${bundle.counts.verified}`,
    `- Draft: ${bundle.counts.draft}`,
    `- Partial: ${bundle.counts.partial}`,
    '',
    '## Verification Matrix',
    ...bundle.verificationCapabilityMatrix.map(
      (capability) => `- ${capability.label}: ${capability.status} (arithmetic: ${capability.arithmeticSupport})`,
    ),
    '',
    '## Office URLs',
    ...bundle.officeUrlsStatus.map((urlStatus) => `- ${urlStatus.url}: ${urlStatus.status} - ${urlStatus.details}`),
    '',
    '## Known Warnings',
    ...bundle.knownWarnings.map((warning) => `- ${warning}`),
    '',
    '## Rollback Notes',
    ...bundle.rollbackNotes.map((note) => `- ${note}`),
    '',
  ].join('\n')
}

function buildHtml(bundle) {
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>Release Evidence ${escapeHtml(bundle.commitHash)}</title>`,
    '</head>',
    '<body>',
    `<pre>${escapeHtml(buildMarkdown(bundle))}</pre>`,
    '</body>',
    '</html>',
  ].join('\n')
}

function buildStatus(status, label, details) {
  return {
    status,
    label,
    details,
    checkedAt: generatedAt,
  }
}

function sanitizeFileSegment(value) {
  return value.replace(/[^a-zA-Z0-9._-]/g, '-')
}

function escapeHtml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}
